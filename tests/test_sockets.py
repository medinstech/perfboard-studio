def test_they_sit_on_the_board_go_in_with_the_connectors_and_the_angled_ones_want_an_edge() -> None:
    for archetype in ("pin-socket", "pin-header-ra", "pin-socket-ra"):
        assert archetype in SEATED_ARCHETYPES
        assert PHASE_BY_ARCHETYPE[archetype] == PHASE_BY_ARCHETYPE["pin-header"]
    assert {"pin-header-ra", "pin-socket-ra"} <= EDGE_SEEKING_ARCHETYPES
    # A standing socket mostly holds a module, which has no reason to be on an edge.
    assert "pin-socket" not in EDGE_SEEKING_ARCHETYPES


def _notes(doc: PerfDocument, ref: str, language: str = "en") -> list[str]:
    from perfboard_studio.guide import GuideOptions

    guide = build_guide(doc, LOOKUP, GuideOptions(language=language))
    return [
        note
        for phase in guide.phases
        for step in phase.steps
        if getattr(step, "ref", None) == ref
        for note in getattr(step, "notes", ())
    ]


@pytest.mark.parametrize(
    ("rotation", "side"), [(0, "bottom"), (90, "left"), (180, "top"), (270, "right")]
)
def test_the_guide_says_which_edge_a_right_angle_strip_points_to(rotation: int, side: str) -> None:
    doc = make_doc(components=(component("J1", "hdr-1x3-ra", hole(10, 8), rotation=rotation),))
    assert any(f"point to the {side} edge" in note for note in _notes(doc, "J1"))
    doc = make_doc(components=(component("J2", "skt-1x3-ra", hole(10, 8), rotation=rotation),))
    assert any(f"openings face the {side} edge" in note for note in _notes(doc, "J2"))


def test_a_standing_strip_has_no_facing_note_and_the_turkish_guide_says_it_in_turkish() -> None:
    doc = make_doc(components=(component("J1", "skt-1x3", hole(10, 8)),))
    assert not any("Right angle" in note for note in _notes(doc, "J1"))
    doc = make_doc(components=(component("J1", "hdr-1x3-ra", hole(10, 8)),))
    assert any(note.startswith("90°: pinleri yatık") for note in _notes(doc, "J1", "tr"))


def test_the_step_model_is_the_body_drc_measures_lying_flat() -> None:
    """The board leaves as the solids DRC measured: a right-angle strip is a box from its legs
    to the tips of its pins, one pitch high per row."""
    doc = make_doc(components=(component("J1", "hdr-2x3-ra", hole(10, 8)),))
    parts = board_model(doc, LOOKUP)
    boxes = [s.shape for part in parts[1:] for s in part.solids if isinstance(s.shape, Box)]
    assert len(boxes) == 1
    low, high = boxes[0].low, boxes[0].high
    assert high[2] - low[2] == pytest.approx(2 * PITCH)
    assert sorted((high[0] - low[0], high[1] - low[1])) == pytest.approx(
        sorted((3 * PITCH, PITCH / 2 + PITCH + 10.04))
    )

"""Female headers (skt-) and right-angle headers and sockets (hdr-...-ra, skt-...-ra).

A female header is the pin header's strip with a contact in every hole, so it is held to
the header's pins and numbering. A right-angle strip lies flat past its last row and is
MEANT to reach past the board's edge on that side, so the edge rule and the placer measure
it without that side (``footprints.edge_box``) and everything else still sees all of it.
"""

from __future__ import annotations

import dataclasses

import pytest

from perfboard_studio.drc import run_drc
from perfboard_studio.footprints import (
    REACHES_PAST_EDGE_BY_ARCHETYPE,
    RIGHT_ANGLE_REACH_MM,
    body_extent,
    edge_box,
    get_footprint,
    pin_socket_footprint,
    right_angle_header_footprint,
    standard_footprints,
)
from perfboard_studio.geometry import all_pin_holes
from perfboard_studio.guide import PHASE_BY_ARCHETYPE, build_guide
from perfboard_studio.model import SEATED_ARCHETYPES, STANDARD_PITCH_MM, PerfDocument
from perfboard_studio.placer import EDGE_SEEKING_ARCHETYPES, PlacementWeights
from perfboard_studio.step_export import Box, board_model

from .test_placer import BOARD, _scorer_for, component, hole, make_doc

PITCH = STANDARD_PITCH_MM
LOOKUP = get_footprint


def _footprint(footprint_id: str):
    footprint = get_footprint(footprint_id)
    assert footprint is not None, footprint_id
    return footprint



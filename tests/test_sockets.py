def test_the_edge_box_is_the_body_for_every_other_part() -> None:
    for footprint in standard_footprints().values():
        assert edge_box(footprint, PITCH) == body_extent(footprint, PITCH).box, footprint.id


@pytest.mark.parametrize("footprint_id", ["hdr-1x4-ra", "skt-2x4-ra"])
def test_the_edge_box_stops_half_a_pitch_past_the_legs(footprint_id: str) -> None:
    footprint = _footprint(footprint_id)
    rows = max(pin.d_row for pin in footprint.pins) + 1
    body = body_extent(footprint, PITCH).box
    edge = edge_box(footprint, PITCH)
    assert edge[:3] == pytest.approx(body[:3])
    assert edge[3] == pytest.approx((rows - 1) * PITCH + PITCH / 2)
    assert set(REACHES_PAST_EDGE_BY_ARCHETYPE) == set(RIGHT_ANGLE_REACH_MM)


def _overhangs(doc: PerfDocument) -> list[str]:
    return [v.message for v in run_drc(doc, LOOKUP) if v.rule == "component-overhangs-edge"]


@pytest.mark.parametrize(
    ("rotation", "anchor"),
    # Pins along the bottom row pointing down; along the top row pointing up; down the
    # left column pointing left; down the right column pointing right.
    [(0, (8, 15)), (180, (11, 0)), (90, (0, 4)), (270, (23, 7))],
)
def test_a_right_angle_header_pointing_off_its_edge_is_not_an_overhang(
    rotation: int, anchor: tuple[int, int]
) -> None:
    part = component("J1", "hdr-1x4-ra", hole(*anchor), rotation=rotation)
    doc = make_doc(components=(part,))
    footprint = _footprint("hdr-1x4-ra")
    assert all(0 <= h.col < BOARD.cols and 0 <= h.row < BOARD.rows
               for _pin, h in all_pin_holes(part, footprint))
    assert _overhangs(doc) == []


def test_the_same_header_one_hole_in_is_still_not_an_overhang_and_a_box_there_is() -> None:
    """Not vacuous: the whole body DOES reach past the edge, and a part that is not meant to
    -- a box of the same reach -- is reported where the header is not."""
    header = component("J1", "hdr-1x4-ra", hole(8, 14))
    assert _overhangs(make_doc(components=(header,))) == []
    footprint = _footprint("hdr-1x4-ra")
    assert body_extent(footprint, PITCH).box[3] + 14 * PITCH > (BOARD.rows - 0.5) * PITCH
    box = component("X1", "box-4x1-p1-r1-10x12x3-o0x5", hole(8, 14))
    assert len(_overhangs(make_doc(components=(box,)))) == 1


@pytest.mark.parametrize("mirrored", [False, True])
@pytest.mark.parametrize("footprint_id", ["hdr-1x4-ra", "skt-2x3-ra", "skt-1x5", "hdr-2x2-ra"])
def test_the_placer_and_drc_agree_on_every_strip_at_every_edge(
    footprint_id: str, mirrored: bool
) -> None:
    """The one-predicate rule ``test_placer`` holds the registry to, for the new strips."""
    board = dataclasses.replace(BOARD, cols=40, rows=40)
    footprint = _footprint(footprint_id)
    checked = 0
    for rotation in (0, 90, 180, 270):
        probe = dataclasses.replace(
            component("X1", footprint_id, hole(0, 0), rotation=rotation), mirrored=mirrored
        )
        pins = [h for _pin, h in all_pin_holes(probe, footprint)]
        min_c, max_c = min(h.col for h in pins), max(h.col for h in pins)
        min_r, max_r = min(h.row for h in pins), max(h.row for h in pins)
        for inset in (0, 1, 3):
            for anchor in (
                hole(inset - min_c, 20),
                hole(board.cols - 1 - inset - max_c, 20),
                hole(20, inset - min_r),
                hole(20, board.rows - 1 - inset - max_r),
            ):
                doc = make_doc(components=(dataclasses.replace(probe, anchor=anchor),), board=board)
                state, scorer = _scorer_for(doc, LOOKUP, PlacementWeights())
                assert scorer.full(state).overhanging_parts == len(_overhangs(doc)), (
                    footprint_id, rotation, anchor,
                )
                checked += 1
    assert checked == 4 * 3 * 4



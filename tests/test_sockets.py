@pytest.mark.parametrize("size", ["1x1", "1x4", "1x15", "2x3", "2x20"])
@pytest.mark.parametrize("suffix", ["skt-{}", "hdr-{}-ra", "skt-{}-ra"])
def test_a_strip_has_the_pin_headers_pins_and_numbering(size: str, suffix: str) -> None:
    """A header and the socket it goes into name the same pin the same way."""
    strip = _footprint(suffix.format(size))
    header = _footprint(f"hdr-{size}")
    assert strip.id == suffix.format(size)
    assert strip.pins == header.pins
    assert not strip.polarized


@pytest.mark.parametrize(
    ("footprint_id", "archetype", "height"),
    [
        ("skt-1x4", "pin-socket", 8.5),
        ("skt-2x4", "pin-socket", 8.5),
        ("hdr-1x4-ra", "pin-header-ra", 2.54),
        ("hdr-2x4-ra", "pin-header-ra", 5.08),
        ("skt-1x4-ra", "pin-socket-ra", 2.54),
        ("skt-2x4-ra", "pin-socket-ra", 5.08),
    ],
)
def test_each_strip_is_its_archetype_at_its_height(
    footprint_id: str, archetype: str, height: float
) -> None:
    footprint = _footprint(footprint_id)
    assert footprint.body.archetype == archetype
    assert footprint.body_height == pytest.approx(height)
    assert footprint.body.dims["height"] == pytest.approx(height)


@pytest.mark.parametrize("footprint_id", ["skt-3x4", "skt-3x4-ra", "hdr-3x4-ra", "skt-1x0"])
def test_a_strip_of_three_rows_or_none_is_not_a_footprint(footprint_id: str) -> None:
    assert get_footprint(footprint_id) is None


def test_the_generators_refuse_what_the_grammar_never_asks_for() -> None:
    with pytest.raises(ValueError, match="1 or 2 rows"):
        pin_socket_footprint(rows=3, cols=2)
    with pytest.raises(ValueError, match="1 or 2 rows"):
        right_angle_header_footprint(rows=0, cols=2)


def test_none_of_them_is_in_the_registry() -> None:
    """The registry is frozen to the original's 61; a new family is generated by its id."""
    for footprint_id in standard_footprints():
        assert not footprint_id.startswith("skt-") and not footprint_id.endswith("-ra")


def test_a_socket_is_a_header_sized_moulding_eight_and_a_half_tall() -> None:
    """One pitch per hole round the pins, as a pin header's moulding is."""
    assert body_extent(_footprint("skt-1x6"), PITCH).box == pytest.approx(
        body_extent(_footprint("hdr-1x6"), PITCH).box
    )
    assert body_extent(_footprint("skt-2x5"), PITCH).box == pytest.approx(
        body_extent(_footprint("hdr-2x5"), PITCH).box
    )


@pytest.mark.parametrize(("rows", "female"), [(1, False), (2, False), (1, True), (2, True)])
def test_a_right_angle_body_runs_from_its_legs_to_the_tips_kicad_measures(
    rows: int, female: bool
) -> None:
    """KiCad 10's _Horizontal strips: a header's plastic 1.5 to 4.04 mm past its last row
    and its pins to 10.04, a socket's moulding 1.52 to 10.03. The body is the legs over
    their holes, half a pitch round, out to the far end of whatever lies flat."""
    footprint = _footprint(f"{'skt' if female else 'hdr'}-{rows}x5-ra")
    archetype = "pin-socket-ra" if female else "pin-header-ra"
    body_from, body_to, reach = RIGHT_ANGLE_REACH_MM[archetype]
    assert (body_from, body_to, reach) == (
        (1.52, 10.03, 10.03) if female else (1.5, 4.04, 10.04)
    )
    dims = footprint.body.dims
    assert (dims["bodyFrom"], dims["bodyTo"], dims["pinReach"]) == (body_from, body_to, reach)
    assert dims["width"] == pytest.approx(body_to - body_from)

    last_row = (rows - 1) * PITCH
    min_x, max_x, min_y, max_y = body_extent(footprint, PITCH).box
    assert (min_x, max_x) == pytest.approx((-PITCH / 2, 4 * PITCH + PITCH / 2))
    assert (min_y, max_y) == pytest.approx((-PITCH / 2, last_row + reach))
    # The courtyard is the same box: nothing else can stand under the legs or the pins.
    xs = [p.x for p in footprint.body_outline]
    ys = [p.y for p in footprint.body_outline]
    assert (min(xs), max(xs), min(ys), max(ys)) == pytest.approx((min_x, max_x, min_y, max_y))


def test_the_body_stays_on_its_legs_at_another_pitch() -> None:
    """From the pins at the board's pitch, the reach in millimetres."""
    footprint = _footprint("hdr-2x3-ra")
    _min_x, _max_x, min_y, max_y = body_extent(footprint, 2.0).box
    assert (min_y, max_y) == pytest.approx((-1.0, 2.0 + 10.04))


